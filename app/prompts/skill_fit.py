METHOD = """\
[전제 — 반드시 읽어라]
쓸 수 있는 근거는 **프로젝트 안에 있는 것뿐**이다.
   (1) 참여자가 이 프로젝트에서 맡은 역할 (PM / BE / FE / QA / DESIGN / INFRA)
   (2) 참여자가 이 프로젝트에서 처리한 할 일의 제목
이 둘은 프로젝트 화면에 이미 보이는 정보다.

다음은 조회할 수 없고, 추측해서도 안 된다.
   - 입사일 · 근속연차 (데이터에 없다)
   - 이 프로젝트 밖에서의 경력 · 다른 프로젝트 이력
   - 개인의 역량 · 숙련도 · 성과
   - 후보군 표에 없는 사람 (존재 여부조차 알 수 없다)

[판단 절차]
1. 대상 작업이 어떤 성격인지 먼저 규정한다. 제목만으로 모호하면 그렇게 적고 넘어간다.
2. 그 성격에 해당하는 역할을 맡은 참여자를 matches 에 **순위 없이** 나열한다.
   basis 에는 위 (1)(2) 중 무엇을 봤는지 구체적으로 적는다.
   - 좋은 예: "이 프로젝트 BE 역할. 알림 센터 API·권한 정책 재설계를 처리했다"
   - 나쁜 예: "백엔드에 능숙함" (근거가 어디서 나왔는지 알 수 없다)
3. 해당 역할을 맡은 사람이 없으면 matches 를 비우고 unresolved 에 적는다.
   후보군 표 밖에서 사람을 찾지 마라. 그 표가 전부다.
4. 명백한 부재(승인된 휴가)가 컨텍스트에 보이면 note 에 한 줄 남긴다.

[하지 말 것]
- 점수 · 순위 · "1순위/2순위" 같은 서열 표현. 이 축은 서열을 내지 않는다
- "A가 B보다 적합하다" 같은 사람 간 비교
- 컨텍스트에 없는 이름을 만들어내는 것. 후보군 표에 없으면 없는 사람이다
- 그 사람이 지금 바쁜지로 판단하는 것. 그건 가용성 축의 일이다
"""
