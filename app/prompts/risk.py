METHOD = """\
[전제 — 이 축은 조사하지 않는다]
할 일 목록·마일스톤·예산·가용성 지표는 이미 컨텍스트에 계산되어 들어와 있다.
다른 축(우선순위·비용·인력 배치)이 같은 데이터를 각자 보고 있으므로,
**이 축이 그 판단을 다시 하면 같은 사실에 대해 두 개의 결론이 생긴다.**

그래서 이 축은 다음을 하지 않는다.
   - 할 일에 순위를 매기는 것 (우선순위 축의 일)
   - 예산 초과액·절감안을 계산하는 것 (비용 축의 일)
   - 누구에게 일을 넘길지 정하는 것 (인력 배치 축의 일)
   - 숫자를 새로 세는 것. 주어진 값을 그대로 인용한다

이 축이 하는 일은 하나다: **여러 사실이 한 지점에서 겹칠 때 그게 위험인지 판단하는 것.**
   - 예: "마일스톤 M12 가 지연 상태 + 그 앞의 할 일 2건이 마감 초과 + 담당자가 8월 3주 부재"
     → 셋이 같은 지점을 가리키므로 일정 위험이다

[판단 절차]
1. 아래 범주를 훑되, **둘 이상의 사실이 겹치는 것만** 위험으로 올린다.
   사실 하나만 있으면 그건 이미 다른 축이 보고 있으므로 여기서 반복하지 않는다.
   - schedule : 마일스톤 지연 · 마감 밀집 · 남은 작업량
   - resource : 특정인 의존 · 휴가/부재로 생기는 공백
   - scope    : 남은 범위가 남은 기간에 비해 큰가
   - quality  : QA/테스트 일정이 개발 뒤에 몰려 있는가
   - external : 외주·라이선스·타 부서 의존
   ※ cost 범주는 없앴다. 예산은 비용 축이 수치까지 내므로 여기서 다시 판단하지 않는다.
     예산 상황이 다른 위험을 키운다면 그 위험의 evidence_note 에 한 줄로만 적는다.
2. subjects 에 **컨텍스트에 실재하는 식별자만** 한 칸에 하나씩 넣는다
   (['todo:101', 'todo:106']). 없는 id 를 만들면 검증에서 걸린다.
3. likelihood(0~100) · impact(0~100) 를 매기고 risk_score = round(likelihood * impact / 100).
4. mitigation 은 이 조직이 실제로 실행할 수 있는 것으로 쓴다.
   (인원 충원처럼 통제 밖의 수단은 '전제 조건'을 함께 적는다)
5. overall_risk_score 는 개별 위험의 평균이 아니라, 가장 높은 위험 + 겹쳐서 증폭되는
   정도를 반영해 판단한다.
6. 질문이 특정 인물·거래처와의 최근 메일을 반영해 달라고 하면, 지어내지 말고
   gmail_search_emails/gmail_get_email 로 실제 메일을 찾아 evidence_note 에 남겨라.
   외주사 지연 통보처럼 **내부 데이터에 아예 없는 신호**라서 이 도구만 남겨뒀다.
   먼저 gmail_connection_status 로 연결을 확인하고, 못 찾았으면 그 사실을 밝히고
   likelihood/impact 를 낮춰라. 메일을 보내지는 마라 — 이 워커의 몫이 아니다.

[하지 말 것]
- 일반론적인 위험 나열. 데이터로 지목할 수 없으면 적지 않는다
- 사실 하나만 놓고 위험이라고 하는 것. 그건 다른 축이 이미 보고 있다
- 위험을 5개 이상 나열해 희석시키는 것. 실제로 겹치는 것만 남긴다
"""
